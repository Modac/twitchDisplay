# PlatformIO pre-build script: writes .pio/build_info/build_info.h with
#  - FW_VERSION: the git version (e.g. "fa42d53" or "v1.0-3-gfa42d53-dirty")
#  - FONT_BIN_CRC: the CRC of fonts/font.bin (built by tools/make_fonts.py),
#    compared with the font partition's
# A header instead of -D flags: the version changes with every commit, and a
# define on the command line would rebuild every file (framework and
# libraries included); the header is only included by src/twitchDisplay.cpp,
# so cached builds stay incremental. It is rewritten only when it changes.
Import("env")
import os
import struct
import subprocess

project = env.subst("$PROJECT_DIR")
try:
    version = subprocess.check_output(
        ["git", "describe", "--always", "--tags", "--dirty"],
        cwd=project, stderr=subprocess.DEVNULL,
    ).decode().strip()
except Exception:
    version = "unknown"

try:
    with open(os.path.join(project, "fonts", "font.bin"), "rb") as f:
        head = f.read(16)
    font_crc = struct.unpack("<I", head[12:16])[0] if head[:8] == b"TDFONT01" else 0
except OSError:
    font_crc = 0

out_dir = os.path.join(project, ".pio", "build_info")
os.makedirs(out_dir, exist_ok=True)
header = ("// generated by tools/version.py\n"
          '#define FW_VERSION "%s"\n'
          "#define FONT_BIN_CRC 0x%08xUL\n") % (version.replace('"', ""), font_crc)
path = os.path.join(out_dir, "build_info.h")
try:
    with open(path) as f:
        current = f.read()
except OSError:
    current = None
if current != header:
    with open(path, "w") as f:
        f.write(header)

env.Append(CPPPATH=[out_dir])
print("Firmware version: %s, font.bin CRC: %08x" % (version, font_crc))
